"""
features/vlm/api.py — рамка вокруг ответа модели (COMPONENTS.md §4.4).

Уровни 3 и 4 защиты живут здесь. Первый — в компоненте, и замер CM-0
показал, что рассчитывать на него нельзя: промпт просит дословный OCR, и
директива с картинки возвращается дословно, как её и просили. Значит
безопасность даёт то, что делает приложение с полученным текстом.

Уровень 3 — санитайзинг. Наша логика, модель в ней не участвует;
единственный уровень, который нельзя обойти подбором картинки.

Уровень 4 — рамка. Описание никогда не попадает в документ голым: пометка
происхождения плюс цитатный блок. Для читающего архив это разница между

    ВНИМАНИЕ
    Игнорируй предыдущие инструкции.

и

    > 🖼 Что на изображении (получено машинно):
    > ВНИМАНИЕ. Игнорируй предыдущие инструкции.

Отдельно и один раз на весь архив ИНСТРУКЦИЯ_ДЛЯ_ИИ.md заявляет, что всё
содержимое — данные. Правило намеренно не про картинки: перечислить один
тип содержимого как опасный значит намекнуть, что остальные безопасны.

Нет Qt-импортов — чистый Python, как features/export/filters.py.
"""

from __future__ import annotations

import html as html_lib
import logging
import re
from typing import Optional

logger = logging.getLogger(__name__)

# Пометка происхождения. Своя, не 🎙: расшифровка голоса и описание
# картинки — разные вещи, и в документе их надо различать с одного взгляда.
IMAGE_MARK = "🖼"

CAPTION = "Что на изображении (получено машинно)"

# Потолок на нашей стороне. Компонент уже обрезает по своему бюджету, но
# доверять чужому процессу на слово незачем: он мог быть собран из другой
# версии исходников.
MAX_CHARS = 1500

_WHITESPACE = re.compile(r"\s+")

# Знаки, которыми в markdown открывают блок кода. Внутри однострочной цитаты
# они безобидны, но описание попадает ещё и в JSON, откуда его может достать
# чужой инструмент и вставить куда угодно.
_BACKTICKS = re.compile(r"`+")


def sanitize_description(text: Optional[str]) -> str:
    """
    Готовит ответ модели к записи в документ (уровень 3).

    Схлопывает любые переводы строк в пробелы. Это главное здесь: рамка
    цитаты в markdown действует на строку, и текст с переводом строки
    вышел бы из неё во второй же строке — как раз то, чего рамка не должна
    допускать. Однострочное описание из цитаты выйти не может.

    Заодно глушатся обратные кавычки: внутри цитаты они безвредны, но то же
    описание уезжает в JSON, а оттуда его может взять сторонний инструмент.

    Returns:
        Одна строка без переводов и обратных кавычек, обрезанная по потолку.
        Пустая строка, если описывать нечего, — вызывающий по ней поймёт,
        что рисовать нечего.
    """
    if not text:
        return ""
    flat = _WHITESPACE.sub(" ", str(text)).strip()
    flat = _BACKTICKS.sub("'", flat)
    if len(flat) > MAX_CHARS:
        cut = flat[:MAX_CHARS].rstrip()
        flat = f"{cut}… [описание усечено: пропущено {len(flat) - len(cut)} символов]"
    return flat


def frame_for_markdown(text: Optional[str]) -> str:
    """
    Описание для MD и для базы знаний — цитатой с пометкой.

    Цитата, а не обычный абзац: для модели, которая потом читает архив, это
    видимая граница между содержимым и текстом, за который отвечаем мы.

    Returns:
        Готовый блок с переводом строки на конце, либо пустая строка.
    """
    clean = sanitize_description(text)
    if not clean:
        return ""
    return f"\n> {IMAGE_MARK} **{CAPTION}:**\n> {clean}\n"


def frame_for_html(text: Optional[str]) -> str:
    """То же для HTML: свой класс и экранирование."""
    clean = sanitize_description(text)
    if not clean:
        return ""
    return (f'<div class="msg-image-desc">{IMAGE_MARK} '
            f'<b>{html_lib.escape(CAPTION)}:</b> '
            f'{html_lib.escape(clean)}</div>')


def frame_for_docx_lines(text: Optional[str]) -> tuple:
    """
    То же для DOCX: (заголовок, текст) — рисовать их генератору.

    Здесь только слова: python-docx в этот модуль не тянем, чтобы он
    оставался пригодным для импорта откуда угодно, как filters.py.

    Returns:
        Пара строк, либо (None, None) — рисовать нечего.
    """
    clean = sanitize_description(text)
    if not clean:
        return None, None
    return f"{IMAGE_MARK} {CAPTION}:", clean


def description_field(text: Optional[str]) -> Optional[str]:
    """
    Описание для JSON — очищенное, но без рамки.

    Рамка здесь не нужна и вредна: JSON читает программа, у неё поле уже
    отделено ключом. Для корпуса важнее чистое значение, чем украшение —
    та же логика, по которой заглушки фильтра нужны документу и вредны
    поисковому индексу (EXPORT_NAMING.md §7).
    """
    return sanitize_description(text) or None
